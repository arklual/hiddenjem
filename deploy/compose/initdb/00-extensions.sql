-- =============================================================================
--  00 — расширения PostgreSQL
-- =============================================================================
--  Выполняется контейнером postgres-init от имени bootstrap-суперпользователя.
--  Скрипт обязан быть ИДЕМПОТЕНТНЫМ: он прогоняется при каждом `make up`.
--
--  Расширения ставятся в схему `public`, а не в схему сервиса, потому что тип
--  (vector) должен быть виден всем, кто его использует, и не должен
--  дублироваться. Право CREATE на `public` при этом отзывается (30-grants.sql),
--  так что общей «свалки» не возникает.
-- =============================================================================

\echo '[00-extensions] vector'

-- pgvector — эмбеддинги документов и терминов, vector(384) (§4 модели данных, ADR-0009).
-- Образ pgvector/pgvector:pg16 содержит расширение; на «ванильном» postgres:16
-- эта строка упадёт — это осознанный ранний отказ, а не деградация.
CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA public;

-- pg_stat_statements — без него разбор инцидента «медленная база» превращается
-- в гадание. Требует shared_preload_libraries, поэтому включаем мягко.
DO $$
BEGIN
    CREATE EXTENSION IF NOT EXISTS pg_stat_statements WITH SCHEMA public;
EXCEPTION WHEN OTHERS THEN
    RAISE NOTICE '[00-extensions] pg_stat_statements недоступно (%): пропускаем', SQLERRM;
END
$$;
