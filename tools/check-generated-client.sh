#!/usr/bin/env bash
# =============================================================================
#  Сгенерированный клиент соответствует контракту
# =============================================================================
#  `frontend/src/api/generated.ts` порождается из OpenAPI и коммитится. Правило
#  «перегенерировать после каждой правки контракта» записано в самом скрипте
#  генерации и до сих пор не удерживалось ничем.
#
#  Цена расхождения не в самом файле, а в том, что оно незаметно: проверки
#  соответствия Zod-схем типам (`schemas.ts`) продолжают проходить, потому что
#  обе стороны устарели одинаково. Клиент описывает прошлую версию API, а сборка
#  зелёная.
#
#  Проверка генерирует во временный файл и сравнивает. Рабочее дерево не
#  трогается: проверка, перезаписывающая то, что проверяет, после неудачи
#  оставляет изменённый репозиторий — и её начинают запускать реже.
# =============================================================================
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
COMMITTED="$ROOT/frontend/src/api/generated.ts"
EXPECTED="$(mktemp)"
trap 'rm -f "$EXPECTED"' EXIT

if [[ ! -f "$COMMITTED" ]]; then
    echo "  ✗ нет $COMMITTED — запустите: npm --prefix frontend run gen:api" >&2
    exit 1
fi

HORIZON_GEN_OUT="$EXPECTED" node "$ROOT/frontend/scripts/gen-api.mjs" >/dev/null

if ! diff -q "$COMMITTED" "$EXPECTED" >/dev/null; then
    echo "  ✗ клиент разошёлся с контрактом. Запустите: npm --prefix frontend run gen:api" >&2
    diff "$COMMITTED" "$EXPECTED" | head -40 >&2
    exit 1
fi

echo "клиент соответствует контракту"
