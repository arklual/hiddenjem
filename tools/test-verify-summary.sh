#!/usr/bin/env bash
#
# Учёт пропущенных проверок в `tools/verify.sh`.
#
# Зачем отдельный тест у скрипта проверок. Гейт — это то, что производит уверенность: зелёный итог
# читают вместо чтения кода. До этой правки итог печатал «Все проверки пройдены» независимо от того,
# сколько проверок выполнилось: пропуски нигде не накапливались, и на машине без JDK, npm и PyYAML
# гейт сообщал об успехе, не проверив ничего, и возвращал ноль. Ошибка такого рода не заметна
# никогда — она выглядит ровно как успех.
#
# Проверяется поведение, а не текст ради текста: пропуск обязан попасть в итог, формулировка
# «все проверки пройдены» обязана исчезнуть, а в строгом режиме пропуск обязан вернуть ненулевой код.
#
# Цель `java` со сломанным JAVA_HOME выбрана потому, что пропускается мгновенно и ничего не
# собирает. Цель `contracts` здесь не годится: этот тест вызывается из неё, и вызов был бы
# бесконечным.

set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

failures=0

check() { # check <название> <ожидание> <факт>
  if [[ "$2" == "$3" ]]; then
    printf '  ✓ %s\n' "$1"
  else
    printf '  ✗ %s: ожидалось «%s», получено «%s»\n' "$1" "$2" "$3"
    failures=$((failures + 1))
  fi
}

contains() { # contains <название> <подстрока> <текст>
  if [[ "$3" == *"$2"* ]]; then
    printf '  ✓ %s\n' "$1"
  else
    printf '  ✗ %s: в итоге нет «%s»\n' "$1" "$2"
    failures=$((failures + 1))
  fi
}

lacks() { # lacks <название> <подстрока> <текст>
  if [[ "$3" != *"$2"* ]]; then
    printf '  ✓ %s\n' "$1"
  else
    printf '  ✗ %s: в итоге осталось «%s»\n' "$1" "$2"
    failures=$((failures + 1))
  fi
}

# JAVA_HOME указывает на несуществующий путь — ровно тот случай, что был на живой машине:
# `tools/env.sh` задавал MAVEN_HOME на неустановленный Maven, и JVM-половина гейта пропускалась.
#
# PATH — пустой каталог, а не `/usr/bin:/bin`. Прежний вариант предполагал, что в системных
# каталогах JDK нет, и на машине разработчика это было верно; на раннере GitHub `/usr/bin/javac`
# существует, проверка находила компилятор, пропуска не случалось — и тест падал на всём подряд,
# сообщая «учёт пропусков сломан» там, где сломано было его собственное допущение. Пустой каталог
# делает отсутствие JDK свойством запуска, а не свойством машины.
#
# `/bin/bash` по абсолютному пути: с пустым PATH `env` не нашёл бы интерпретатор по имени. Ничего
# внешнего целевой ветке гейта не нужно — время он считает встроенным SECONDS, цвета задаёт
# литералами, наличие обёртки проверяет `-x`.
sandbox="$(mktemp -d)"
trap 'rm -rf "$sandbox"' EXIT
# В песочнице лежит ровно то, без чего гейт не найдёт сам себя: `dirname` из первой строки, где
# он вычисляет корень репозитория. Всё остальное на этом пути — встроенные средства оболочки.
# Компилятора и Maven здесь нет и быть не может, поэтому пропуск случается по той причине, ради
# которой тест написан, а не по случайной.
ln -s "$(command -v dirname)" "$sandbox/dirname"
broken_env=(env JAVA_HOME=/nonexistent MAVEN_HOME=/nonexistent "PATH=$sandbox")

printf 'пропуск попадает в итог\n'
out="$("${broken_env[@]}" /bin/bash tools/verify.sh java 2>&1)"
code=$?
check "код возврата — ноль: локально пропуск не провал" 0 "$code"
contains "итог называет число пропущенных" "пропущено: 1" "$out"
contains "итог перечисляет, что именно не проверено" "JDK не найден" "$out"
lacks "формулировки «все проверки пройдены» больше нет" "Все проверки пройдены" "$out"

printf 'строгий режим считает пропуск провалом\n'
out="$("${broken_env[@]}" /bin/bash tools/verify.sh java --strict 2>&1)"
code=$?
check "код возврата — ненулевой" 1 "$code"
contains "названа причина ненулевого кода" "Строгий режим" "$out"

printf 'строгий режим включается и переменной окружения\n'
out="$("${broken_env[@]}" HORIZON_VERIFY_STRICT=1 /bin/bash tools/verify.sh java 2>&1)"
code=$?
check "код возврата — ненулевой" 1 "$code"

if [[ $failures -gt 0 ]]; then
  printf '\n✗ учёт пропусков сломан: %d\n' "$failures"
  exit 1
fi
printf '\n✓ учёт пропусков в verify.sh работает\n'
