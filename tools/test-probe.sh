#!/usr/bin/env bash
#
# Поведение `tools/probe.sh` — инструмента, которым проверяется несущесть тестов.
#
# Проверять сам инструмент проверки не педантизм: три раза за одну сессию подмена «прошла успешно»
# по причинам, к предмету проверки отношения не имевшим — несовпавший якорь, несработавшее
# восстановление, неверный разделитель тестов. Каждый раз вывод выглядел как успех. Инструмент
# написан, чтобы эти случаи стали отказом; здесь проверяется, что они им стали.
#
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

failures=0
check() { # check <название> <ожидаемый код> <фактический код>
  if [[ "$2" == "$3" ]]; then printf '  ✓ %s\n' "$1"
  else printf '  ✗ %s: ожидался код %s, получен %s\n' "$1" "$2" "$3"; failures=$((failures + 1)); fi
}

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
subject="$work/subject.txt"

printf 'ЗНАЧЕНИЕ=правильное\n' > "$subject"
# «Тест» проверяет, что в файле правильное значение. Ломается подменой — как настоящий.
cat > "$work/check.sh" <<CHECK
#!/usr/bin/env bash
grep -q 'ЗНАЧЕНИЕ=правильное' "$subject"
CHECK
chmod +x "$work/check.sh"

printf 'подмена, которую проверка ловит\n'
./tools/probe.sh "$subject" "правильное" "сломанное" -- "$work/check.sh" >/dev/null 2>&1
check "код возврата — ноль: подмена поймана" 0 $?
cmp -s <(printf 'ЗНАЧЕНИЕ=правильное\n') "$subject"
check "файл восстановлен побайтово" 0 $?

printf 'подмена, которой проверка не замечает\n'
# Меняем то, на что «тест» не смотрит. Это не поимка, и инструмент обязан сказать это кодом.
./tools/probe.sh "$subject" "ЗНАЧЕНИЕ" "ЗНАЧЕНЬЕ" -- true >/dev/null 2>&1
check "код возврата — ненулевой: подмена не поймана" 1 $?

printf 'якорь, которого в файле нет\n'
# Тот самый случай: подменять нечего, проверка проходит, и это ничего не значит. Молчаливый успех
# здесь однажды был засчитан за поимку.
./tools/probe.sh "$subject" "такого текста нет" "X" -- true >/dev/null 2>&1
check "код возврата — отказ, а не успех" 2 $?
cmp -s <(printf 'ЗНАЧЕНИЕ=правильное\n') "$subject"
check "файл не тронут" 0 $?

printf 'команда проверки меняет каталог\n'
# Именно так подменённый код однажды остался в дереве: относительный путь после `cd` указывал не
# туда. Инструмент приводит путь к абсолютному до запуска команды.
# Команда именно проверяет файл, а не падает всегда: первая версия этого случая делала `exit 1`
# безусловно, то есть сама была примером сломанной проверки — и новое правило её отвергло, как
# и должно было. Инструмент оказался прав против собственного теста.
./tools/probe.sh "$subject" "правильное" "сломанное" \
    -- bash -c "cd /tmp && grep -q 'ЗНАЧЕНИЕ=правильное' '$subject'" >/dev/null 2>&1
check "код возврата — ноль: подмена поймана" 0 $?
cmp -s <(printf 'ЗНАЧЕНИЕ=правильное\n') "$subject"
check "файл восстановлен, несмотря на смену каталога" 0 $?

printf 'сама проверка сломана\n'
# Тот класс ошибки, ради которого инструмент и писался, и который он сначала пропускал: команда
# падает по своей причине — неверный путь, опечатка в имени теста, неверный разделитель, — а выглядит
# это как пойманная подмена. Поймано на первом же применении к настоящему коду.
./tools/probe.sh "$subject" "правильное" "сломанное" -- /нет/такой/команды >/dev/null 2>&1
check "код возврата — отказ, а не мнимая поимка" 4 $?
cmp -s <(printf 'ЗНАЧЕНИЕ=правильное\n') "$subject"
check "файл не тронут" 0 $?

if [[ $failures -gt 0 ]]; then printf '\n✗ инструмент проб сломан: %d\n' "$failures"; exit 1; fi
printf '\n✓ проба ведёт себя так, как обещает\n'
