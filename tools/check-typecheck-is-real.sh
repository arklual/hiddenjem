#!/usr/bin/env bash
# Проверяет, что проверка типов фронтенда действительно что-то проверяет.
#
# `frontend/tsconfig.json` — solution-style: он не перечисляет исходников, только ссылки. Поэтому
# `tsc --noEmit` против него компилирует НОЛЬ файлов и завершается успехом. Именно так гейт и жил:
# «tsc ✓» при четырнадцати ошибках типов в приложении.
#
# Ошибку такого рода нельзя поймать самим тайпчекером — он не падает. Ловится она только
# подсчётом: если в компиляцию не попало ни одного файла проекта, проверять было нечего.
set -euo pipefail

cd "$(dirname "$0")/.."
count=$(npx --prefix frontend tsc -p frontend/tsconfig.app.json --noEmit --listFiles 2>/dev/null \
  | grep -c "^${PWD}/frontend/src/" || true)

if [[ "$count" -lt 50 ]]; then
  echo "проверка типов охватывает всего $count файлов проекта — гейт холостой или почти холостой" >&2
  exit 1
fi
echo "проверка типов охватывает $count файлов проекта"
