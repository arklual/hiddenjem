#!/usr/bin/env bash
#
# Проверка несущести теста подменой боевого кода.
#
#   ./tools/probe.sh <файл> <якорь> <замена> -- <команда проверки...>
#
# Ломает код, запускает проверку, восстанавливает файл и говорит, поймала ли проверка поломку.
# Тест, который не краснеет от снятой возможности, ничего не проверяет — а выглядит так же, как
# работающий.
#
# Зачем отдельный инструмент, а не три строки в терминале. Три строки я писал десятки раз и трижды
# ошибся так, что ошибка выглядела успехом:
#
#   1. Якорь не совпал с текстом файла. Подмена не применилась, проверка прошла — и «BUILD SUCCESS»
#      читался как «поймано», хотя ломать было нечего.
#   2. Восстановление сорвалось: `cd` внутри скрипта сменил каталог, относительный путь перестал
#      разрешаться. Подменённый код остался в дереве, и следующий полный прогон гейта пошёл по нему.
#   3. Проверка прошла, потому что подмена ничего не сломала, — и это был честный результат, но
#      отличить его от первого случая по выводу было нельзя.
#
# Поэтому здесь: якорь обязателен и его отсутствие — отказ, а не тишина; путь приводится к
# абсолютному до всякой работы; восстановление сверяется побайтово; а «подмена не поймана» — это
# ненулевой код возврата, а не строка в выводе, которую можно проглядеть.
#
set -uo pipefail

c_red=$'\033[31m'; c_green=$'\033[32m'; c_yellow=$'\033[33m'; c_bold=$'\033[1m'; c_off=$'\033[0m'
die() { printf '%s✗ %s%s\n' "$c_red" "$1" "$c_off" >&2; exit "${2:-2}"; }

[[ $# -ge 5 ]] || die "использование: probe.sh <файл> <якорь> <замена> -- <команда...>"

file="$1"; anchor="$2"; replacement="$3"; shift 3
[[ "$1" == "--" ]] || die "перед командой проверки нужен разделитель --"
shift

# Абсолютный путь сразу: команда проверки почти всегда меняет каталог, и относительный путь после
# неё указывает не туда. Именно так подменённый код однажды остался в дереве.
file="$(cd "$(dirname "$file")" && pwd)/$(basename "$file")"
[[ -f "$file" ]] || die "нет такого файла: $file"

backup="$(mktemp)"
cp "$file" "$backup"

restore() {
    cp "$backup" "$file"
    # Побайтовая сверка, а не «мы скопировали и всё хорошо». Невосстановленный боевой код — худший
    # исход этого инструмента: он тихо отравляет все последующие прогоны.
    if ! cmp -s "$backup" "$file"; then
        die "ФАЙЛ НЕ ВОССТАНОВЛЕН: $file — сверьтесь с $backup вручную" 3
    fi
    rm -f "$backup"
}

# Проверка обязана проходить на нетронутом коде. Без этого условия проба бессмысленна: команда,
# упавшая по своей причине — неверный путь к интерпретатору, опечатка в имени теста, неверный
# разделитель у Surefire, — выглядит точно так же, как пойманная подмена. Так и вышло на первом же
# применении этого инструмента к настоящему коду: путь к venv сломался из-за `env -C`, команда
# упала, и проба доложила «подмена поймана», ничего не подменив по существу.
#
# Прогон удваивает время. Это дешевле, чем ложная уверенность в тесте, который на самом деле не
# проверяет ничего.
printf '%s▸ проверка на нетронутом коде%s\n' "$c_bold" "$c_off"
if ! "$@"; then
    rm -f "$backup"
    die "проверка не проходит и без подмены — сначала почините её, результат пробы ничего не значит" 4
fi

if ! grep -qF -- "$anchor" "$file"; then
    rm -f "$backup"
    die "якорь не найден в $file — подменять нечего, результат проверки ничего не значит"
fi

python3 - "$file" "$anchor" "$replacement" <<'PY' || { restore; die "не удалось применить подмену"; }
import pathlib, sys

path, anchor, replacement = pathlib.Path(sys.argv[1]), sys.argv[2], sys.argv[3]
text = path.read_text(encoding="utf-8")
if anchor not in text:
    raise SystemExit(1)
path.write_text(text.replace(anchor, replacement, 1), encoding="utf-8")
PY

printf '%s▸ подмена применена: %s%s\n' "$c_bold" "$(basename "$file")" "$c_off"
"$@"
verdict=$?
restore

if [[ $verdict -ne 0 ]]; then
    printf '%s✓ подмена поймана (проверка упала)%s\n' "$c_green" "$c_off"
    exit 0
fi

printf '%s✗ подмена НЕ поймана: проверка прошла на сломанном коде%s\n' "$c_red" "$c_off"
printf '%s  Три причины, и вывод у них одинаков:\n' "$c_yellow"
printf '   1. проверка запущена не там, где живёт покрытие — сузив её до одного класса, легко\n'
printf '      получить «не поймано» на правиле, которое проверяется соседним. Прежде чем считать\n'
printf '      это находкой, повторите пробу на всём наборе;\n'
printf '   2. подмена не меняет поведения — тогда это честный результат, а не пробел;\n'
printf '   3. тест действительно ничего не проверяет.\n'
printf '  Различить их можно только глядя на код.%s\n' "$c_off"
exit 1
