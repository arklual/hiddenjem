/**
 * Порядок разбора очереди пополнения словаря направлений.
 *
 * Журнал копит формулировки, которых словарь не знает. Порядок в нём — не оформление: куратор
 * разбирает очередь сверху и до тех пор, пока не кончится время, поэтому наверх обязано попадать
 * то, что дороже стоит продукту.
 *
 * Дороже всего формулировка, на которую продукт **не предложил ничего**. Там, где подсказка была,
 * аналитик в одном щелчке от нужного направления — потеря измеряется секундами. Там, где подсказки
 * не было, он получил красную плашку и ушёл ни с чем: это направление, о котором продукт не знает
 * вовсе, и таких в словаре не хватает по-настоящему.
 *
 * Внутри каждой группы — по частоте: одна и та же дыра, о которую споткнулись двадцать раз, важнее
 * той, о которую споткнулись однажды.
 */
import type { UnrecognizedDirection } from '@/api/types';

export function queueOrder(rows: readonly UnrecognizedDirection[]): UnrecognizedDirection[] {
  return [...rows].sort((left, right) => {
    if (left.hadAWayOut !== right.hadAWayOut) {
      return left.hadAWayOut ? 1 : -1;
    }
    if (left.occurrences !== right.occurrences) {
      return right.occurrences - left.occurrences;
    }
    // Последний ключ — нормализованная форма: порядок обязан быть функцией данных, иначе два
    // открытия одного экрана дают разные списки и куратор не может вернуться к тому, что видел.
    return left.normalizedQuery.localeCompare(right.normalizedQuery);
  });
}
