/**
 * Что сказать аналитику, когда анализ не выполнен.
 *
 * До этого разбора в заголовке критического уведомления стоял сырой код — «Анализ не выполнен:
 * ASSEMBLY_FAILED», — а в теле приходило исключение движка вида «ZeroDivisionError: float division
 * by zero» (`analyze_domain._fail` шлёт `f"{type(error).__name__}: {error}"`). Это читается в тот
 * момент, когда аналитику важнее всего понять, что делать дальше, и не отвечает ни на один его
 * вопрос.
 *
 * Правила:
 *
 * 1. Каждому известному коду отвечает объяснение и следующее действие. Не «что сломалось внутри», а
 *    «что это значит для вас».
 * 2. Неизвестный код — движок вправе завести новый — не должен приводить к пустому месту или к коду
 *    в заголовке. Общий честный ответ лучше и того, и другого.
 * 3. Технические подробности сохраняются, но подчинённо: поддержке они нужны, аналитику мешают.
 * 4. Возможность повтора берётся из ответа службы, а не угадывается по коду: служба знает про
 *    попытку то, чего таблица здесь знать не может.
 */
import type { AnalysisParameters } from '@/api/types';

/**
 * Границы контракта (`AnalysisParameters` в OpenAPI). Поправка, вышедшая за них, дала бы запрос,
 * который служба отклонит: кнопка, ведущая к отказу, хуже отсутствия кнопки.
 */
const LIMITS = {
  yearsWindow: { min: 3, max: 15, fallback: 7 },
  topN: { min: 5, max: 50, fallback: 15 },
} as const;

export interface FailureExplanation {
  /** Заголовок: что произошло, человеческими словами. */
  title: string;
  /** Что это значит и почему так вышло. */
  explanation: string;
  /** Что аналитику делать дальше. */
  nextStep: string;
}

