/**
 * Общий ответ на код, которого здесь нет.
 *
 * Движок вправе завести новый код, и релиз его таблицы объяснений отстанет от релиза движка.
 * Показать в этот момент сырой код значило бы вернуться ровно к тому, ради чего таблица заведена.
 */
const UNKNOWN: FailureExplanation = {
  title: 'Анализ не выполнен',
  explanation: 'Расчёт остановился по причине, которую интерфейс пока не умеет объяснить словами.',
  nextStep: 'Повторите запуск. Если повторяется — сообщите код ниже в поддержку.',
};

export function explainFailure(code: string | undefined): FailureExplanation {
  if (!code) {
    return UNKNOWN;
  }
  return EXPLANATIONS[code.trim().toUpperCase()] ?? UNKNOWN;
}

/** Поправка к параметрам, которую предлагает совет, вместе с человеческим описанием изменения. */
export interface FailureCorrection {
  parameters: AnalysisParameters;
  /** Что именно изменено — показывается до запуска, а не применяется молча. */
  note: string;
}

function clamp(value: number, limits: { min: number; max: number }): number {
  return Math.min(limits.max, Math.max(limits.min, value));
}

/**
 * Поправка ровно та, что обещает текст совета.
 *
 * Совет, который нельзя выполнить в один щелчок, — половина совета: «расширьте окно анализа»
 * заставляет аналитика вернуться к поиску и набрать запрос заново. Здесь тот же совет становится
 * действием.
 *
 * Поправка не применяется молча. Аналитик мог выставить параметры намеренно, и подменённый за его
 * спиной прогон дал бы отчёт, которого он не просил, — а сравнивать его с предыдущим было бы не с
 * чем. Поэтому возвращается предложение, которое интерфейс показывает до запуска.
 *
 * Кодов без осмысленной поправки больше, чем с ней, и это правильно: выдуманная поправка хуже
 * простого повтора, потому что выглядит как знание причины.
 */
export function correctionFor(
  code: string | undefined,
  parameters: AnalysisParameters | undefined,
): FailureCorrection | undefined {
  const current = parameters ?? {};
  const window = current.yearsWindow ?? LIMITS.yearsWindow.fallback;
  const topN = current.topN ?? LIMITS.topN.fallback;

  switch (code?.trim().toUpperCase()) {
    case 'NO_DOCUMENTS_FOUND':
    case 'ASSEMBLY_FAILED': {
      const widened = clamp(window + 3, LIMITS.yearsWindow);
      if (widened === window) {
        // Окно уже предельное. Предлагать «расширить» то, что расширить некуда, значит обещать
        // невозможное — честнее не предлагать ничего.
        return undefined;
      }
      return {
        parameters: { ...current, yearsWindow: widened },
        note: `Окно анализа будет расширено с ${window} до ${widened} лет.`,
      };
    }
    case 'RESOURCE_EXHAUSTED': {
      const narrowed = clamp(window - 2, LIMITS.yearsWindow);
      const fewer = clamp(topN - 5, LIMITS.topN);
      if (narrowed === window && fewer === topN) {
        return undefined;
      }
      return {
        parameters: { ...current, yearsWindow: narrowed, topN: fewer },
        note: `Окно анализа будет сужено до ${narrowed} лет, число тем — до ${fewer}.`,
      };
    }
    default:
      // Сбой инфраструктуры, таймаут, недоступный срез: причина не в параметрах, и менять их —
      // значит делать вид, что причина известна.
      return undefined;
  }
}

/** Есть ли для кода собственное объяснение — нужно тестам и отладке, не интерфейсу. */
export function hasExplanation(code: string | undefined): boolean {
  return code !== undefined && code.trim().toUpperCase() in EXPLANATIONS;
}
