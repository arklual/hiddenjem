/**
 * Что сказать читателю о диапазоне места темы (методология §16).
 *
 * Веса шести индикаторов выбраны экспертно. Диапазон «с 2-го по 11-е место при разумных изменениях
 * весов» — единственное, что отличает вывод о направлении от вывода о наших настройках, и это
 * различие меняет решение: тему, держащуюся при любом взвешивании, несут в комитет, а тему,
 * вылетающую из списка при удвоении одного веса, сначала проверяют руками.
 *
 * Правило вынесено из разметки, потому что оно является утверждением о надёжности, а не оформлением.
 * Ошибка здесь тише прочих: подпись «место не зависит от весов» под темой, которая зависит, ничего
 * не ломает и никем не замечается — кроме того, кто примет по ней решение.
 */

export type StabilityVerdict =
  /** Место не менялось ни при одном наборе весов — самое сильное, что можно сказать. */
  | 'immovable'
  /** Место плавает, но тема остаётся в отчёте при любом взвешивании. */
  | 'holds'
  /** При некоторых весах тема выпадает из отчёта: её присутствие — следствие выбора весов. */
  | 'slips';

export interface StabilityRange {
  best: number;
  worst: number;
}

/**
 * Отсутствие диапазона возвращает `null` — «не измеряли», а не «неустойчиво».
 *
 * Так приходят отчёты, выпущенные до появления проверки. Подставить им вывод об устойчивости
 * значило бы объявить надёжным то, что никто не измерял, а ложная оговорка о надёжности
 * обесценивает настоящие.
 */
export function verdictFor(
  stability: StabilityRange | undefined,
  topN: number,
): StabilityVerdict | null {
  if (!stability) {
    return null;
  }
  if (stability.best === stability.worst) {
    return 'immovable';
  }
  return stability.worst <= topN ? 'holds' : 'slips';
}
