/**
 * На чём держится кейс-пример — словами, которые можно проверить.
 *
 * Методология §8 подбирает пример тремя правилами разного веса: патент с корпоративным
 * правообладателем, публикация с корпоративной аффилиацией, наиболее цитируемая академическая
 * группа. До появления этого модуля все три приводили к одной подписи — «организация, у которой тема
 * уже перешла в практическую плоскость».
 *
 * Замер по эталонному корпусу показал цену упрощения: из 90 тем на патенте держатся 29, на
 * публикации — 61, и 21 из них на препринте. То есть в двух случаях из трёх продукт утверждал
 * переход в практику, имея на руках статью. Патент означает, что организация закрепила право на
 * применение; публикация означает, что организация над темой работает. Комитет, называющий компанию
 * вслух, различает эти два утверждения — если ему дать различить.
 *
 * Функция чистая и лежит отдельно от разметки: подпись — это утверждение о доказательстве, и оно
 * проверяется тестом, а не осмотром экрана.
 */
import type { CaseExample } from '@/api/types';

export type CaseBasis = NonNullable<CaseExample['basis']>;

export interface CaseBasisNote {
  /** Короткая подпись рядом с названием организации. */
  readonly label: string;
  /** Что именно измерено — и чего из этого не следует. */
  readonly detail: string;
  /** Насколько сильно свидетельство: решает оформление, а не смысл. */
  readonly strength: 'strong' | 'moderate' | 'weak';
}

const NOTES: Readonly<Record<CaseBasis, CaseBasisNote>> = {
  PATENT: {
    label: 'Патент компании',
    detail: 'Организация закрепила право на применение — это самое сильное из трёх оснований.',
    strength: 'strong',
  },
  CORPORATE_PUBLICATION: {
    label: 'Публикация компании',
    detail:
      'Организация работает над темой. Внедрения это не означает: основание — статья, а не патент и не продукт.',
    strength: 'moderate',
  },
  ACADEMIC_GROUP: {
    label: 'Академическая группа',
    detail:
      'Корпоративного следа у темы пока нет — ни патента с правообладателем, ни публикации компании.',
    strength: 'weak',
  },
};

/**
 * Подпись для основания; `null`, если основание неизвестно.
 *
 * Неизвестное основание — это отчёт, выпущенный до появления поля, а не ошибка. Отсутствие подписи
 * честнее выдуманной: подставить сюда «публикацию» по умолчанию значило бы утверждать то, чего
 * никто не измерял.
 */
export function caseBasisNote(basis: CaseExample['basis']): CaseBasisNote | null {
  if (basis === undefined) {
    return null;
  }
  return NOTES[basis] ?? null;
}
