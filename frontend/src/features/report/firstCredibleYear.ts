/**
 * Почему график начинается раньше, чем «первое достоверное упоминание».
 *
 * Величина считается по BRULE-2: первый год, в котором тему подтверждают не меньше двух документов
 * из не меньше чем двух организаций. Одиночное раннее упоминание правило не засчитывает — и это
 * верно для оценки новизны, но на карточке рядом стоит график, у которого столбик есть и раньше.
 *
 * Замер по эталонному корпусу: у **71 темы из 90** документы появляются раньше названного года, у
 * **21** — на два года и больше. Худший случай: `donor templates`, документы с 2019, подпись 2023.
 *
 * Читатель, заметивший расхождение, видит продукт, спорящий сам с собой в двух соседних элементах.
 * Подпись объясняет разницу там, где она видна, и молчит там, где её нет: оговорка под каждой темой
 * приучает не читать оговорки.
 */
import type { RankedTrend } from '@/api/types';

export interface EarlierMentions {
  /** Первый год, в котором по теме есть хотя бы один документ. */
  readonly since: number;
  /** На сколько лет он раньше названного достоверного года. */
  readonly gap: number;
}

/**
 * Разрыв между первым годом с документами и первым достоверным годом; `null`, если его нет.
 *
 * `null` возвращается и когда ряда нет вовсе: тогда сказать нечего, а выдуманный ноль означал бы
 * измеренное совпадение.
 */
export function earlierMentions(trend: RankedTrend): EarlierMentions | null {
  const years = (trend.timeline ?? [])
    .filter((point) => point.documentCount > 0)
    .map((point) => Number.parseInt(point.period.slice(0, 4), 10))
    .filter((year) => Number.isFinite(year));

  if (years.length === 0 || !trend.firstMentionYear) {
    return null;
  }

  const since = Math.min(...years);
  const gap = trend.firstMentionYear - since;

  return gap > 0 ? { since, gap } : null;
}
