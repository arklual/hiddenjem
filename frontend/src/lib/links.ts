/**
 * Адрес внешнего источника, пригодный для атрибута href.
 *
 * Адреса приходят из препринтов, патентов и RSS-лент — публиковать ленту может кто угодно.
 * `href="javascript:…"` React не блокирует: он предупреждает в разработке и всё равно отрисовывает
 * ссылку, а клик по ней исполняет код в сессии аналитика. `data:text/html` открывает страницу
 * злоумышленника в новой вкладке. И то и другое достижимо из внешнего источника до самого отчёта.
 *
 * Решение то же, что уже принято в выгрузке для комитета: источник назван, ссылка не поставлена.
 * Молча выбрасывать строку нельзя — она и есть доказательство, ради которого отчёт существует;
 * молча делать её кликабельной — тем более.
 */
const WEB_SCHEMES = ['http:', 'https:'];

export function safeHref(url: string | null | undefined): string | undefined {
  if (!url) return undefined;
  try {
    // Разбор, а не сравнение префиксов: «\tjavascript:alert(1)» и «JaVaScRiPt:» проходят проверку
    // на startsWith, но браузером трактуются как схема javascript. Нормализует их сам разборщик
    // URL — проверено: у всех трёх написаний protocol равен «javascript:». Именно поэтому здесь
    // задаётся вопрос разборщику, а не строке: он отвечает то же, что ответит браузер.
    //
    // trim ниже к безопасности отношения не имеет и это проверено подменой: без него разбор даёт
    // тот же протокол. Он лишь убирает пробелы из возвращаемого значения, чтобы они не уезжали в
    // атрибут href.
    const parsed = new URL(url);
    return WEB_SCHEMES.includes(parsed.protocol) ? url.trim() : undefined;
  } catch {
    // Относительный или разрушенный адрес: у внешнего источника его быть не должно, а трактовать
    // его как путь внутри приложения — значит выдать чужую строку за свою страницу.
    return undefined;
  }
}
