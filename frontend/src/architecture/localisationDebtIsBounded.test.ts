const FROZEN_LITERALS = 372;
const FROZEN_FILES = 35;

const CYRILLIC = /[А-Яа-яЁё]/;

function sourceFiles(): string[] {
  const found: string[] = [];
  const walk = (dir: string): void => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(full);
      } else if (/\.(tsx|ts)$/.test(entry.name)) {
        found.push(full);
      }
    }
  };
  walk(SRC);
  // Словарь исключён: он и есть место, где русскому тексту положено быть. Тесты — тоже: их читает
  // разработчик, и они по-русски намеренно.
  return found.filter((path) => !path.includes(`${'i18n'}`) && !path.includes('.test.'));
}

/**
 * Русские строковые литералы файла — без комментариев: они читателю интерфейса не видны.
 *
 * **Считаются только литералы в кавычках.** Текст, стоящий прямо в разметке (`<span>Профиль:</span>`),
 * в число не попадает, и это ограничение замера, а не оценка продукта: обойти его значило бы
 * разбирать JSX, а не читать файл. Поэтому число ниже — нижняя граница долга, а не его полный
 * размер, и читать его как «столько всего непереведённого» нельзя.
 *
 * Ограничение найдено на собственной правке: подпись профиля в заголовке отчёта не сдвинула счёт.
 */
function russianLiterals(source: string): string[] {
  const code = source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
  const literals: string[] = [];
  for (const match of code.matchAll(/'([^'\\]*)'|"([^"\\]*)"/g)) {
    const value = match[1] ?? match[2] ?? '';
    if (CYRILLIC.test(value)) literals.push(value);
  }
  return literals;
}

function measure(): { files: number; literals: number } {
  let files = 0;
  let literals = 0;
  for (const path of sourceFiles()) {
    const count = russianLiterals(readFileSync(path, 'utf8')).length;
    if (count > 0) {
      files += 1;
      literals += count;
    }
  }
  return { files, literals };
}

describe('the localisation debt is measured and cannot grow silently', () => {
  it('scans a plausible number of files', () => {
    // Канарейка обхода: пустой список файлов дал бы ноль строк и вечнозелёную проверку, которая
    // при этом читалась бы как «весь интерфейс переведён».
    // Порог снижен с 80 до 60 вместе с удалением входа, профиля и администрирования пользователей.
    expect(sourceFiles().length).toBeGreaterThan(60);
  });

  it('counts a literal only inside code, never inside a comment', () => {
    // Комментарии в этом проекте по-русски намеренно и читателю интерфейса не видны. Считая их,
    // замер измерял бы качество документации, а не долг локализации.
    const sample = [
      "// 'комментарий со строкой'",
      '/* и такой тоже: "строка" */',
      "const shown = 'видимая строка';",
      "const latin = 'plain text';",
    ].join('\n');

    expect(russianLiterals(sample)).toEqual(['видимая строка']);
  });

  it('keeps the debt at or below what was measured', () => {
    const { literals } = measure();

    expect(literals).toBeLessThanOrEqual(FROZEN_LITERALS);
  });

  it('keeps the number of affected files at or below what was measured', () => {
    const { files } = measure();

    expect(files).toBeLessThanOrEqual(FROZEN_FILES);
  });

  it('fails when the frozen number silently goes stale', () => {
    // Без этого заморозка обманывает: строки переведены, число осталось прежним, и проверка
    // пропускает новый долг под видом старого. То же требование стоит у заморозки потерь правила
    // границы, и по той же причине.
    const { files, literals } = measure();

    expect({ files, literals }).toEqual({ files: FROZEN_FILES, literals: FROZEN_LITERALS });
  });
});
