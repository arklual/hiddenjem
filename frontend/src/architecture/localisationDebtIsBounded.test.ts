/**
 * Сколько текста интерфейса минует словарь — и почему это число заморожено, а не обнулено.
 *
 * Английский объявлен выбираемой локалью (переключатель стоял в профиле и ушёл вместе с ним). Два предыдущих исправления
 * закрыли словарь (57 непереведённых ключей) и заголовки ошибок, приходящие по проводу. Оба верны и
 * оба касались малой доли текста: **в словаре 166 ключей, а строк с кириллицей вне его — 322 в 54
 * файлах**. Английская локаль покрывает сквозной словарь и не покрывает тексты страниц.
 *
 * Что именно покрыто, видно по составу словаря: ошибки (61 ключ), общие подписи (22), оговорки (22),
 * навигация (18), перечисления и подсказки к индикаторам, стадиям, устойчивости. То есть переведено
 * то, что встречается на каждом экране и решает, поймёт ли читатель предупреждение. Не переведены
 * тексты, написанные под конкретную страницу.
 *
 * Заморожено, а не обнулено, по двум причинам, и обе записаны, чтобы к ним не возвращаться заново.
 *
 * 1. **Триста двадцать две строки — это не механическая работа.** Тексты этого продукта объясняют
 *    методологические решения («корпус рассмотрен не целиком: сузьте направление или окно»), и
 *    перевод без носителя языка даёт английский хуже, чем его отсутствие.
 * 2. **Заказчик и комитет говорят по-русски.** Английский здесь — удобство, а не требование, и
 *    честнее сказать, что он частичный, чем изображать полноту.
 *
 * Проверка запрещает долгу расти: новая русская строка в разметке краснеет и заставляет автора
 * решить — ключ в словарь или осознанная запись в это число. Ровно так же заморожены потери правила
 * границы (`test_real_names_are_not_lost.py`): замораживается не ноль, а достигнутое.
 * 339 → 343 (56 → 57 файлов): поле направления научилось отвечать на вопрос «а что сюда писать» —
 * вердикт по формулировке до запуска, подсказка «возможно, вы имели в виду» и перечень известных
 * направлений с поиском. Четыре строки в новом файле, и прибавка сознательная: без них аналитик
 * узнавал, что формулировка не подошла, только из готового отчёта — после полутора минут ожидания
 * и списанного слота квоты. Это подписи страницы, а не оговорки, и по принятому правилу они
 * остаются в долге.
 *
 * 343 → 344 (57 → 58 файлов): подписи, объясняющие графики отчёта — что за линия под баллом, что
 * означают квадранты карты, что показывает радар. Прибавка сознательная и того же рода, что
 * предыдущие: это тексты страниц, а не сквозные оговорки. Молчащий график хуже непереведённого:
 * непереведённое можно прочесть со словарём, а росчерк без подписи не читается никак.
 *
 */
const SRC = resolve(__dirname, '..');

