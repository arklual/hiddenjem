"""Настройки сервиса. Всё — переменными окружения (12-factor), секретов в коде нет."""

from __future__ import annotations

from pydantic_settings import BaseSettings, SettingsConfigDict

__all__ = ["Settings", "settings"]


class Settings(BaseSettings):
    """Конфигурация сервиса вывода моделей.

    Назначение модели на шаг **статическое и раскрытое** — требование ТЗ §3.1: «допускается
    использование нескольких моделей при обязательном раскрытии формата выбора модели для
    конкретного ответа и явного логирования». Автоматического выбора модели здесь нет: каждый
    эндпоинт жёстко связан с одной моделью, имя которой возвращается в ответе и пишется в лог.
    """

    model_config = SettingsConfigDict(env_prefix="HORIZON_NLP_", extra="ignore")

    port: int = 8086
    log_level: str = "INFO"

    #: Перевод EN→RU. Marian (opus-mt) — маленькая детерминированная модель-переводчик, а не
    #: генеративная: на перевод названия технологии генеративная модель отвечает пересказом.
    translate_en_ru_model: str = "Helsinki-NLP/opus-mt-en-ru"
    #: Перевод RU→EN. Нужен поиску: предметные коды источников и сами источники англоязычные.
    translate_ru_en_model: str = "Helsinki-NLP/opus-mt-ru-en"
    #: Сколько строк переводится одним проходом. Больше — быстрее, но длиннее хвост латентности.
    translate_batch_size: int = 16
    #: Потолок длины строки в токенах. Абстракт длиннее обрезается — перевод целой статьи не
    #: нужен ни одному экрану, а обрезка честнее молчаливого отказа.
    translate_max_tokens: int = 512

    #: Генеративная модель: семантические суждения («это название технологии?») и русское резюме.
    #: Разворачивается локально через ollama, веса — GGUF с Hugging Face.
    generative_base_url: str = "http://horizon-llm:11434"
    generative_model: str = "horizon-qwen3.5-4b"
    generative_timeout_seconds: float = 600.0
    #: Режим рассуждения выключен: Qwen3.5 тратит на него сотни токенов, а на процессоре это
    #: минуты. Замер на стенде: 2.8 токена в секунду.
    generative_num_predict: int = 512
    #: Сколько потоков отдаётся генерации. Число измерено, а не выбрано: на стенде (6 ядер в
    #: лимите контейнера) 2 потока дают 5.1 токена в секунду, 4 — 6.1, 6 — 5.0, 8 — 2.7. Задача
    #: упирается в пропускную способность памяти, и лишние потоки только толкаются. Значение
    #: обязано пересматриваться на другом железе — поэтому это настройка, а не константа.
    generative_num_thread: int = 4

    #: Где живёт генеративная модель: ``ollama`` — локально, ``openai`` — облачный API в формате
    #: OpenAI (``/chat/completions``). Выбор статический и раскрытый, как требует ТЗ §3.1:
    #: автоматического переключения между ними нет, имя модели уходит в каждый ответ и в лог.
    #:
    #: Облачный вариант нужен ради скорости. Локальная модель на процессоре стенда читает около
    #: пятнадцати строк за двадцать секунд, и петля семантической проверки упиралась в потолок,
    #: оставляя в отчёте по ИИ пять тем из пятнадцати (разбор 89). ТЗ допускает облачные модели по
    #: API, среди них gpt-5.6-luna.
    generative_backend: str = "ollama"
    #: Адрес OpenAI-совместимого API, например ``https://api.example.ru/v1``.
    openai_base_url: str = ""
    #: Ключ API. Только из окружения — ни в коде, ни в репозитории его нет.
    openai_api_key: str = ""
    #: Глубина рассуждения модели семейства gpt-5: ``low`` — судье и переводу названий глубже не
    #: нужно, а каждый уровень выше стоит секунд и токенов на каждом вызове.
    openai_reasoning_effort: str = "low"

    #: Глубокое исследование (``/deep-research``): агент ищет по открытым каталогам проекта и
    #: читает страницы целиком. Потолки ниже — верхние: запрос может их только понизить, а
    #: бюджет прогона задаёт сервис сбора по режиму анализа — быстрый (5,5 минуты под SLA
    #: в 20) или качественный (до 20 минут в анализе на 30–40).
    research_max_iterations: int = 120
    research_max_fetches: int = 100
    research_time_budget_seconds: float = 1260.0
    #: Глубина рассуждения в цикле исследования — та же ``low``: ход агента короткий, а каждый
    #: уровень выше умножается на три десятка ходов.
    research_reasoning_effort: str = "low"
    #: Как представляться площадкам: имя агента для ``robots.txt`` и адрес для «вежливого пула»
    #: Crossref — тот же, что у сервиса сбора.
    research_user_agent: str = "HorizonBot/1.0"
    research_contact_email: str = "horizon@example.bank"
    #: Токен GitHub необязателен: без него десять поисков в минуту и шестьдесят запросов в час.
    research_github_token: str = ""
    #: Собственный веб-корпус (разбор 110): JSON Lines страниц, собранных заранее с проверкой
    #: robots.txt. Пусто или нет файла — источник ``webcorpus`` недоступен.
    webcorpus_path: str = ""
    #: Сигналы сборщиков веб-корпуса (``signals.jsonl``): имена с адресами страниц-доказательств.
    #: Идут в ``/propose-technologies`` первыми; доказательства — страницы корпуса, а не модель.
    webcorpus_signals_path: str = ""
    #: Панель экспертов по подсферам (граф LangGraph, разбор 110): в ``/propose-technologies``
    #: идут имена, найденные экспертами в своих страницах корпуса, первыми.
    panel_enabled: bool = True
    panel_limit: int = 30
    #: Экспертная стадия перед финалом (``/jury``): три эксперта отвечают «да/нет» по критериям жюри.
    #: Модель — своя настройка: пусто — та же, что у сервиса (ТЗ §3.1: выбор модели раскрыт в ответе).
    jury_model: str = ""

    #: Модели загружаются при старте, а не при первом запросе: иначе первый живой запрос платит
    #: за загрузку весов, и продукт выглядит зависшим ровно в момент показа.
    preload_translation: bool = True


settings = Settings()
