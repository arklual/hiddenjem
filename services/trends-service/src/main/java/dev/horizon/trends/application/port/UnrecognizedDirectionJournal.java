package dev.horizon.trends.application.port;

import java.util.List;
import java.util.UUID;

import dev.horizon.trends.domain.direction.UnrecognizedDirection;

/**
 * Журнал направлений, которых перекрёстный словарь не знает.
 *
 * <p>Порт, а не репозиторий домена: журнал — вспомогательная запись, из которой домен ничего не
 * читает и на которой ни одно правило не держится. Он существует ради того, кто пополняет словарь.
 */
public interface UnrecognizedDirectionJournal {

    /**
     * Записать наблюдение: новая формулировка или ещё один случай уже известной.
     *
     * <p>Реализация обязана быть идемпотентной по паре «организация + нормализованная формулировка»:
     * очередь пополнения сортируется по спросу, и строка на каждый запрос превратила бы её в
     * протокол вместо очереди.
     */
    void record(UnrecognizedDirection observation);

    /**
     * Очередь пополнения словаря: сначала то, что спрашивают чаще.
     *
     * <p>Область — организация. Словарь направлений одного банка — это его исследовательская
     * повестка, и утечка её в соседний банк была бы разглашением, а не удобством.
     */
    List<UnrecognizedDirection> mostAsked(UUID organizationId, int limit);
}
