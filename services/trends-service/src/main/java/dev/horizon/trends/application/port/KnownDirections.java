package dev.horizon.trends.application.port;

import java.util.List;

/**
 * Формулировки направлений, которые движок умеет соотнести с корпусом.
 *
 * <p>Существует ради самого трудного момента аналитика — пустого поля ввода. Система знает, какие
 * формулировки распознаёт, и до этого порта не показывала их: аналитик гадал, а неудачная догадка
 * давала отчёт с оговоркой «направление не распознано» — то есть работу, потраченную впустую.
 *
 * <p>Порт, а не собственный список: второй перечень, собранный на этой стороне, разошёлся бы с тем,
 * по которому идёт отбор, и начал бы предлагать формулировки, которые на деле не распознаются. Он
 * врал бы ровно в том месте, ради которого заведён.
 */
public interface KnownDirections {

    /**
     * Известные формулировки в устойчивом порядке.
     *
     * <p>Пустой список — допустимый ответ, а не отказ: подсказка помогает, но не является условием
     * работы экрана. Движок недоступен — аналитик просто вводит направление сам, как делал раньше.
     */
    List<String> list();
}
