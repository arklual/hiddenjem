package dev.horizon.trends.application.port;

import java.util.List;

/**
 * Предметные коды направления — то, чем размечен корпус.
 *
 * <p>Существует ради шага, который до сих пор пропускался. Перекрёстный словарь «формулировка →
 * коды» в продукте был, но применялся на отборе тем, то есть уже <b>после</b> сбора. Сам же сбор
 * нёс коннекторам сырую формулировку, а те сопоставляли её слова с текстом документов напрямую —
 * документы английские, запрос русский, совпадений нет. «Искусственный интеллект», заглавное
 * направление словаря, заканчивался отказом «не найдено ни одного документа» за секунду.
 *
 * <p>Порт, а не собственная копия словаря: две копии расходятся, и разошедшись, дают худший из
 * возможных исходов — сбор нашёл документы по одному пониманию направления, а отбор пометил отчёт
 * «направление не распознано» по другому. Словарь остаётся у движка, здесь только вопрос к нему.
 */
public interface DirectionCrosswalk {

    /**
     * Коды, которыми стоит искать это направление в источниках.
     *
     * <p>Пустой список — допустимый ответ, а не отказ, и означает он две разные вещи сразу:
     * направления нет в словаре либо оно и так на языке корпуса. Сбор в обоих случаях идёт по
     * словам самого запроса, как шёл раньше, — то есть недоступность движка ухудшает выдачу, но не
     * отменяет работу.
     */
    List<String> targetsFor(String query);

    /**
     * Понимает ли движок эту формулировку — и что предложить, если нет.
     *
     * <p>Тот же вопрос, что задаётся перед сбором, но заданный раньше и ради другого: показать
     * аналитику вердикт до запуска. Раньше он приходил после анализа красной оговоркой поверх
     * готового отчёта — то есть после потраченных полутора минут и слота квоты, и без ответа на
     * вопрос «а как тогда написать».
     */
    Resolution resolve(String query);

    /**
     * @param recognized движок соотнёс формулировку с корпусом
     * @param suggestions ближайшие известные формулировки; пусто, когда ничего похожего нет —
     *     подсказка наугад хуже её отсутствия, потому что выглядит как знание
     */
    record Resolution(boolean recognized, List<String> suggestions) {

        public Resolution {
            suggestions = suggestions == null ? List.of() : List.copyOf(suggestions);
        }

        /** Ответ, когда движок недоступен: вердикта нет, и выдумывать его нельзя. */
        public static Resolution unknown() {
            return new Resolution(true, List.of());
        }
    }
}
