package dev.horizon.trends.domain.report;

/**
 * Уровень доверенности источника — требование ТЗ к отображению каждого источника.
 *
 * <p>Значение выводит движок по правилам методологии (класс источника плюс хост ссылки), а здесь
 * оно только перечислено: пересчитывать его на стороне Java значило бы завести вторую методологию,
 * которая разойдётся с первой (ADR-0016).
 */
public enum Credibility {
    /** Рецензируемая публикация, патентная запись, стандарт, официальный домен ведомства. */
    HIGH,
    /** Препринт, аналитический отчёт, репозиторий организации — первоисточник без рецензии. */
    MEDIUM,
    /** Отраслевое медиа, пресс-релиз, соцсеть, личная площадка: первичный индикатор. */
    LOW
}
