package dev.horizon.trends.domain.report;

import java.util.List;

/**
 * Сколько тем отчёта держатся в нём при любом взвешивании индикаторов (методология §16).
 *
 * <p>Диапазон места у отдельной темы отвечает на вопрос о теме. Комитет задаёт вопрос об отчёте:
 * «насколько вообще этот список — вывод, а не следствие ваших настроек?» Ответ «десять тем из
 * пятнадцати остаются в отчёте при любом из четырнадцати наборов весов» и есть та единственная
 * фраза, ради которой всё измерение делалось.
 *
 * <p>Три числа, а не два. {@code measured} отделяет «не измеряли» от «неустойчиво»: отчёты,
 * выпущенные до появления проверки, диапазона не несут, и доля «0 из 15» для них была бы неправдой
 * — самой опасной из возможных, потому что она выглядит как измерение.
 */
public record StabilitySummary(int total, int measured, int steady) {

    /**
     * Свод по темам отчёта.
     *
     * <p>Тема считается устойчивой, если её худшее место не выходит за пределы этого отчёта. Именно
     * этого отчёта, а не пятнадцати по умолчанию: аналитик мог запросить пять тем, и «выпадает из
     * отчёта» относится к тому списку, который держит в руках читатель.
     */
    public static StabilitySummary of(List<RankedTrend> trends) {
        int measured = 0;
        int steady = 0;
        for (RankedTrend trend : trends) {
            var stability = trend.assessment().rankStabilityOptional();
            if (stability.isEmpty()) {
                continue;
            }
            measured++;
            if (stability.get().holdsInTop(trends.size())) {
                steady++;
            }
        }
        return new StabilitySummary(trends.size(), measured, steady);
    }

    /** Измерялась ли устойчивость вообще — иначе говорить о ней нечего. */
    public boolean known() {
        return measured > 0;
    }

    /**
     * Сколько тем присутствуют в отчёте благодаря выбранным весам.
     *
     * <p>Не «неустойчивые темы», а именно эти: тема может двигаться на десять мест и всё равно
     * оставаться в списке — тогда её присутствие от весов не зависит, хотя порядок зависит.
     */
    public int weightDependent() {
        return measured - steady;
    }
}
