-- Лучшее и худшее место темы при разумных изменениях весов индикаторов (методология §16).
--
-- Веса шести индикаторов выбраны экспертно. Это законный способ, так устроены и Rotolo (2015), и
-- Yoon (2012), — но всё же выбор, и внешнего подтверждения у него нет. Пока продукт молчит об этом,
-- ответ на вопрос «а если бы взвесили иначе — список был бы тем же?» сводится к «доверьтесь нам»,
-- и первым его получает самый скептичный читатель отчёта.
--
-- NULL, а не 0 и не текущее место: отчёты, выпущенные до появления проверки, диапазона не несут, и
-- отсутствие обязано читаться как «не измеряли». Подставить сюда нынешний ранг значило бы объявить
-- каждую старую тему идеально устойчивой — утверждение, которого никто не проверял.
--
-- Обе колонки заполняются вместе: диапазон из одной границы не является диапазоном. Ограничение
-- проверяет именно это, а не только порядок границ.
ALTER TABLE report_trends
    ADD COLUMN rank_stability_best smallint,
    ADD COLUMN rank_stability_worst smallint,
    ADD CONSTRAINT report_trends_rank_stability_range CHECK (
        (rank_stability_best IS NULL AND rank_stability_worst IS NULL)
        OR (rank_stability_best >= 1 AND rank_stability_worst >= rank_stability_best)
    );

COMMENT ON COLUMN report_trends.rank_stability_best IS
    'Лучшее место темы среди перебранных наборов весов; NULL — устойчивость не измерялась.';
COMMENT ON COLUMN report_trends.rank_stability_worst IS
    'Худшее место темы среди перебранных наборов весов; NULL — устойчивость не измерялась.';
