-- Ближайшие известные формулировки для нераспознанного направления.
--
-- Хранится вместе с отчётом, а не считается при чтении: подсказка — часть того, что аналитик видел
-- в момент выдачи. Отчёт, открытый через полгода, обязан показывать ту же оговорку и ту же
-- подсказку, даже если словарь направлений с тех пор пополнили.
--
-- Пусто, когда направление распознано: предлагать переформулировать удавшийся запрос незачем.
ALTER TABLE trend_reports
    ADD COLUMN direction_suggestions varchar(200)[] NOT NULL DEFAULT '{}';

COMMENT ON COLUMN trend_reports.direction_suggestions IS
    'Ближайшие формулировки из перекрёстного словаря; непусто только при direction_recognized = false';
