-- Режим анализа и вывод движка методологии.
--
-- Режим (`fast` — в срок ТЗ, двадцать минут; `quality` — до сорока) меняет корпус, а с ним и ответ,
-- поэтому колонки две, как и у движка в V20: у запроса — «в каком режиме считать» (часть
-- идентичности вопроса, см. `params_discriminator`), у отчёта — «в каком посчитано».
--
-- Умолчание `'fast'` — утверждение о прошлом: до появления режимов всё считалось в срок быстрого.

ALTER TABLE research_requests
    ADD COLUMN mode varchar(16) NOT NULL DEFAULT 'fast';

ALTER TABLE trend_reports
    ADD COLUMN mode varchar(16) NOT NULL DEFAULT 'fast';

-- Движок один — `signals`. Колонку запроса сервис больше не пишет, и новые строки подписывает
-- умолчание. Прежние значения не переписываются: `methodology` у старого запроса — правда о том, чем
-- его считали, а у отчёта (`trend_reports.engine`) это и вовсе подпись, которую показывают.
ALTER TABLE research_requests
    ALTER COLUMN engine SET DEFAULT 'signals';

-- `params_discriminator` не трогается намеренно. Прежние ключи оканчиваются именем движка
-- (`…|methodology`, `…|signals`), новые — именем режима (`…|fast`, `…|quality`), и совпасть они не
-- могут: отчёт выведенного движка не будет выдан как готовый ответ на вопрос, заданный после этой
-- миграции. Отчёты `signals` тоже не переиспользуются — пересчёт дешевле, чем гадать, в каком
-- бюджете сбора они получены.
