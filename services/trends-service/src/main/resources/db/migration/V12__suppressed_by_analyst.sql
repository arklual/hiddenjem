-- Сколько тем скрыто по пометке аналитика «это не технология».
--
-- Поле существует ради честности отбора. Тема убирается из ТОП-N до отбора, поэтому её место
-- занимает следующий кандидат — и без этого числа отчёт выглядел бы так, будто скрытого не было
-- вовсе. Молчаливый фильтр производит уверенность вместо сведений.
--
-- DEFAULT 0 и NOT NULL: отчёты, выпущенные до появления пометок, скрытых тем не имели, и нулём это
-- описывается точно. Значение не пересчитывается задним числом — оно относится к тому прогону,
-- который его записал.
ALTER TABLE trend_reports
    ADD COLUMN suppressed_by_analyst integer NOT NULL DEFAULT 0;

COMMENT ON COLUMN trend_reports.suppressed_by_analyst IS
    'Сколько тем скрыто по пометке аналитика NOISE. Отбор происходит до ТОП-N, поэтому освободившееся место занял следующий кандидат.';
