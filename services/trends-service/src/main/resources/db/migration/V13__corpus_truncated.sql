-- Был ли корпус обрезан пределом профиля до анализа.
--
-- Оговорка приходила от движка и терялась: `ReportAssembler` её не передавал, а `TrendReport`
-- вычислял поле с тем же именем и другим смыслом — «тем найдено меньше запрошенных». Одно имя на
-- два разных факта, и до записки для комитета доезжал не тот.
--
-- Разница важна именно для читателя записки. «Тем меньше пятнадцати» означает, что методология
-- столько и нашла. «Корпус обрезан» означает, что часть литературы вообще не рассматривалась —
-- предел профиля 5000 документов, и на широком направлении он достигается. Это ограничение
-- полноты, а не результат измерения, и молчать о нём нельзя.
--
-- DEFAULT false и NOT NULL: отчёты, выпущенные до появления колонки, оговорки не несли, и ложное
-- «корпус обрезан» задним числом было бы хуже её отсутствия.
ALTER TABLE trend_reports
    ADD COLUMN corpus_truncated boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN trend_reports.corpus_truncated IS
    'Корпус обрезан пределом профиля (max_documents) до анализа: часть литературы не рассматривалась.';
