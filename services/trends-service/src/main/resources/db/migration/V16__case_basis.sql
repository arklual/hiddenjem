-- На чём держится кейс-пример: патент, корпоративная публикация или академическая группа.
--
-- Методология §8 подбирает пример тремя правилами разного веса, но до сих пор наружу уходило только
-- имя организации, а карточка подписывала его одинаково — «организация, у которой тема уже перешла в
-- практическую плоскость». Замер по эталонному корпусу: из 90 тем на патенте держатся 29, на
-- публикации — 61, и 21 из них на препринте. То есть в двух случаях из трёх продукт утверждал
-- переход в практику, имея на руках статью.
--
-- Патент означает, что организация закрепила право на применение; публикация означает, что
-- организация над темой работает. Внедрение из второго не следует, и различие обязано доходить до
-- комитета, который по этой строке называет компанию вслух.
--
-- NULL, а не значение по умолчанию: отчёты, выпущенные до появления поля, основания не несут, и
-- любое проставленное задним числом значение было бы утверждением, которого никто не измерял.
ALTER TABLE report_trends
    ADD COLUMN case_basis varchar(24),
    ADD CONSTRAINT report_trends_case_basis_known CHECK (
        case_basis IS NULL OR case_basis IN ('PATENT', 'CORPORATE_PUBLICATION', 'ACADEMIC_GROUP')
    );

COMMENT ON COLUMN report_trends.case_basis IS
    'Правило §8, подобравшее кейс-пример; NULL — отчёт выпущен до появления поля.';
