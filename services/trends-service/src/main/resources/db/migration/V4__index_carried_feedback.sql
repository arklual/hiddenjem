-- Перенос разметки аналитика между отчётами одного направления (BR-A32).
--
-- Запрос соединяет trend_feedback с trend_reports и отбирает по нормализованному запросу. До этих
-- индексов его обслуживать было нечем: ux_feedback_user_trend упорядочен по
-- (user_id, report_id, trend_key), то есть по префиксу user_id даёт всю разметку аналитика за всё
-- время по всем направлениям, а normalized_query отсеивался только после соединения — по одной
-- строке на каждую его оценку.
--
-- Цена ошибки растёт с историей: чем дольше аналитик пользуется разметкой, тем медленнее у него
-- открывается любой отчёт. Деградация ровно у того пользователя, ради которого функция и сделана,
-- и на горячем пути — GET /reports/{id} с бюджетом 300 мс.

-- Сузить до направления до соединения, а не после.
CREATE INDEX ix_reports_normalized_query ON trend_reports (normalized_query);

-- Порядок колонок — порядок запроса: свои оценки, сгруппированные по теме, свежие первыми.
-- DISTINCT ON забирает первую строку каждой группы, не сортируя результат отдельно.
CREATE INDEX ix_feedback_user_topic_recent
    ON trend_feedback (user_id, trend_key, created_at DESC, id DESC);
