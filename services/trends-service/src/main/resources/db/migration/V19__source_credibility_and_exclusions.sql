-- Требования финального ТЗ, которых у отчёта не было: доверенность источника, русский слой и
-- логика исключения.
--
-- 1. «Для каждого источника система должна отображать наименование, ссылку, дату публикации, тип
--    источника, язык оригинала и уровень доверенности.» Наименование, ссылка, дата и тип у
--    источника были; язык и уровень доверенности — нет. Язык приходил от коннектора и терялся на
--    границе аналитики, уровень не выводился нигде.
--
-- 2. «Интерфейс сервиса и вся аналитическая выдача должны быть представлены на русском языке»;
--    «для зарубежного материала сервис должен предоставить русскоязычное резюме или интерпретацию,
--    сохранив оригинальное название, ссылку, дату публикации и язык источника. При использовании
--    автоматического перевода или генеративного резюме это должно быть отмечено возле источника.»
--    Отсюда `localization` как один блок, а не десяток колонок: оригинал не заменяется, русская
--    строка идёт рядом и несёт имя модели и вид обработки. Колонка одна, потому что читается и
--    пишется этот блок всегда целиком, а поля в нём будут появляться.
--
-- 3. «В веб-интерфейсе должны отображаться … причины исключения зрелых технологий или
--    нерелевантных кандидатов при наличии такой информации.» Отсев конвейера существовал только
--    счётчиками в метриках: число без имён, которое аналитик не может проверить.
--
-- Все колонки с умолчаниями и без NOT NULL там, где значение неизвестно: отчёты, выпущенные до
-- этой миграции, обязаны читаться по-прежнему, а не превращаться в отчёты «с неизвестным языком и
-- нулевой доверенностью».

ALTER TABLE report_trend_evidence
    ADD COLUMN language          char(2),
    ADD COLUMN credibility       varchar(8) NOT NULL DEFAULT 'MEDIUM',
    ADD COLUMN credibility_basis text,
    ADD COLUMN independent       boolean    NOT NULL DEFAULT true,
    ADD CONSTRAINT report_trend_evidence_credibility_known CHECK (
        credibility IN ('HIGH', 'MEDIUM', 'LOW')
    );

COMMENT ON COLUMN report_trend_evidence.language IS
    'Язык оригинала, ISO 639-1; NULL — источник его не сообщил.';
COMMENT ON COLUMN report_trend_evidence.credibility IS
    'Уровень доверенности по правилам методологии; MEDIUM — значение не передавалось.';
COMMENT ON COLUMN report_trend_evidence.credibility_basis IS
    'Правило, присвоившее уровень, словами: ТЗ допускает показывать критерии определения.';
COMMENT ON COLUMN report_trend_evidence.independent IS
    'Самостоятельное свидетельство; false у перепечаток пресс-релизов и личных площадок.';

ALTER TABLE report_trends
    ADD COLUMN low_credibility_only boolean NOT NULL DEFAULT false,
    ADD COLUMN localization         jsonb   NOT NULL DEFAULT '{}'::jsonb;

COMMENT ON COLUMN report_trends.low_credibility_only IS
    'Все источники темы низкой доверенности — отметка, которую требует ТЗ вместо удаления темы.';
COMMENT ON COLUMN report_trends.localization IS
    'Русский слой карточки: перевод рядом с оригиналом, имя модели и вид обработки. {} — моделей не было.';

ALTER TABLE trend_reports
    ADD COLUMN exclusions jsonb NOT NULL DEFAULT '[]'::jsonb;

COMMENT ON COLUMN trend_reports.exclusions IS
    'Причины, по которым кандидаты не попали в отчёт: код, формулировка, число и примеры имён.';
