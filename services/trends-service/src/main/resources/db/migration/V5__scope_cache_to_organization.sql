-- Переиспользование готового отчёта внутри организации (BR-A43).
--
-- ix_requests_cache_lookup был построен без организации, потому что и сам поиск был без неё: любой
-- аналитик получал отчёт, посчитанный кем угодно, — и затем получал 404 при попытке его открыть,
-- потому что видимость была владельческой. Кэш обязан совпадать с видимостью, иначе он называет то,
-- чего не покажет.
--
-- Организация — первой колонкой: это самое избирательное равенство в запросе, и с ней индекс
-- перестаёт просматривать чужие организации вовсе.
CREATE INDEX ix_requests_cache_lookup_org
    ON research_requests (organization_id, normalized_query, params_discriminator, finished_at DESC)
    WHERE status = 'COMPLETED';

