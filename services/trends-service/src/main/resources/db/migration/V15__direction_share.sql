-- Доля документов темы, отнесённых источниками к направлению отчёта.
--
-- Величина, на которой держится сам отбор темы в отчёт: методология относит тему к направлению по
-- предметным кодам её документов, а порог — подъём над базовой долей корпуса. Для узкого
-- направления этот порог опускается до четырнадцати сотых, и тема, у которой к направлению отнесены
-- 7 документов из 48, проходит наравне с темами, у которых отнесены две трети.
--
-- Статистика их не разделяет — разбор четырёх попыток в `docs/01-analysis/32-foreign-topic-findings.md`.
-- Человек разделяет с одного взгляда, если ему эту величину показать; пометка «не технология» у него
-- уже есть, и она убирает тему до отбора в ТОП-N.
--
-- NULL, а не 0: отчёты, выпущенные до появления величины, её не несут, и ноль означал бы, что к
-- направлению не отнесён ни один документ темы, — утверждение, которого никто не проверял.
ALTER TABLE report_trends
    ADD COLUMN direction_share double precision,
    ADD CONSTRAINT report_trends_direction_share_range CHECK (
        direction_share IS NULL OR (direction_share >= 0.0 AND direction_share <= 1.0)
    );

COMMENT ON COLUMN report_trends.direction_share IS
    'Доля документов темы, отнесённых к направлению отчёта; NULL — величина не измерялась.';
