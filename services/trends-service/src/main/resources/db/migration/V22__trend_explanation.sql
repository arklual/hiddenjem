-- Объяснение темы: почему она слабый сигнал и почему у неё такая уверенность.
--
-- ТЗ требует на странице инсайта «объяснение статуса слабого сигнала, причины присвоения
-- соответствующей уверенности модели». Движок присылает строки «заголовок — пояснение», собранные из
-- голосов экспертной стадии, вкладов в балл, расчёта уверенности и источников карточки. Блоком, а не
-- колонками: состав строк меняется вместе с движком, а читаются они всегда целиком.
--
-- Умолчание `[]` — утверждение о прошлом: у отчётов до появления объяснения его не было.

ALTER TABLE report_trends
    ADD COLUMN explanation jsonb NOT NULL DEFAULT '[]'::jsonb;

COMMENT ON COLUMN report_trends.explanation IS
    'Почему тема — слабый сигнал и почему такая уверенность: [{"title", "text"}], от движка анализа';
