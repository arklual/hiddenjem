-- Оговорка «направление не распознано» на отчёте.
--
-- Отличается от `partial` тем, о чём предупреждает. `partial` говорит «мы нашли меньше, чем
-- хотели»; это поле говорит «мы не поняли вопроса»: движок не смог соотнести запрошенное
-- направление со словарём предметных кодов, которым размечен корпус, и его выбор того, что
-- относится к направлению, не несёт информации. Отчёт при этом полон, посчитан и правдоподобен.
--
-- DEFAULT true намеренно: отчёты, выпущенные до появления поля, не должны задним числом получить
-- оговорку, к ним не относящуюся. Оговорка, срабатывающая не по делу, обесценивает настоящие.
ALTER TABLE trend_reports
    ADD COLUMN direction_recognized boolean NOT NULL DEFAULT true;

COMMENT ON COLUMN trend_reports.direction_recognized IS
    'false — движок не соотнёс направление со словарём предметных кодов корпуса; выбор тем не зависит от запроса';
