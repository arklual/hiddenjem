-- Английский перевод заголовка и аннотации для документов на русском и китайском (разбор 93).
--
-- Анализ извлекает термины из английского текста: «федеративное обучение», «联邦学习» и
-- «federated learning» иначе стали бы тремя темами, каждая втрое слабее настоящей. Перевод делает
-- генеративная модель, и он недетерминирован, поэтому делается один раз и хранится здесь: снапшот
-- ссылается на документы, и повторный анализ того же снапшота видит тот же текст.
--
-- Оригинал не трогается — перевод лежит рядом, с моделью и временем (раскрытие по ТЗ §3.1).
ALTER TABLE documents
    ADD COLUMN title_en          text         NULL,
    ADD COLUMN abstract_en       text         NULL,
    ADD COLUMN translated_from   varchar(8)   NULL,
    ADD COLUMN translation_model varchar(120) NULL,
    ADD COLUMN translated_at     timestamptz  NULL;
