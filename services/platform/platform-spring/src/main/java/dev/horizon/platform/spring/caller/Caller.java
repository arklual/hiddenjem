package dev.horizon.platform.spring.caller;

import java.util.UUID;

/**
 * Кто задаёт вопрос — пользователь и его организация.
 *
 * <p>Входа в продукте нет: организация одна, и спрашивает всегда один и тот же пользователь
 * ({@link #SINGLE}). Модель данных при этом сохранена — запуск, оценка темы и отслеживаемое
 * направление по-прежнему принадлежат пользователю, — потому что на этих полях держатся квота,
 * переиспользование готовых отчётов и перенос оценок между версиями отчёта.
 */
public record Caller(UUID userId, UUID organizationId) {

    /**
     * Единственный пользователь и его организация.
     *
     * <p>Идентификаторы прежнего демонстрационного режима — намеренно: под ними на стенде уже лежат
     * все запуски, оценки и отслеживаемые направления, и новый идентификатор оставил бы их чужими.
     */
    public static final Caller SINGLE = new Caller(
            UUID.fromString("0de00000-0000-7000-8000-000000000001"),
            UUID.fromString("0de00000-0000-7000-8000-000000000002"));
}
